using Microsoft.Extensions.Logging;
using PolitikServer.Core;

namespace PolitikServer.TurnResolution;

public class EconomyResolver
{
    private readonly ILogger<EconomyResolver> _logger;
    private readonly EntityLibrary _entities;

    public EconomyResolver(ILogger<EconomyResolver> logger, EntityLibrary entityLibrary)
    {
        _logger = logger;
        _entities = entityLibrary;
    }

    internal void Tick()
    {
        _logger.LogInformation("Starting economy tick...");

        Nation[] allNations = _entities.GetAll<Nation>();

        foreach (Nation nation in allNations)
        {
            NationalEconomy economy = nation.economy.Get();

            // Calculate passive money and power income:
            CalcuateProvincePassives(ref economy, nation);
        
            // Power:
            CalculatePowerGeneration(ref economy, nation);
            CalculatePowerConsumption(ref economy, nation);
            CalculatePowerFulfillment(ref economy);
        }
    }

    /// <summary>
    /// Calcuates the passive power and money generated by all controlled provinces and updates the provided economy object.
    /// </summary>
    private void CalcuateProvincePassives(ref NationalEconomy economy, Nation nation)
    {
        int power = 0;
        int money = 0;

        float population_tax_rate = WorldConfig.GetFloat("economy_population_tax_rate");

        foreach (ProvinceEntity province in nation.provincesControlled.Get())
        {
            if (province.isOccupied)
            {
                // Occupied provinces do not provide any passives.
                continue;
            }

            ProvinceDevelopmentLevel level = province.developmentLevel.Get(); 
            
            power += level.PowerProduced;
            money += (int) MathF.Floor(province.population * population_tax_rate);

            _logger.LogInformation("Province '{province}' provides {power} power and ${money} this turn.", province.UniqueIdentifier, power, money);
        }

        economy.passiveMoney = money;
        economy.passivePower = power;
    }

